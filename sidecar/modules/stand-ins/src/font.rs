//! A 5 by 9 bitmap font for printable ASCII: capitals and digits seven rows
//! tall, two rows below the baseline for descenders. Each row's five bits
//! run left to right from the highest.

pub const WIDTH: usize = 5;
pub const HEIGHT: usize = 9;
/// Columns from one character's left edge to the next's.
pub const ADVANCE: usize = WIDTH + 1;

const BOX: [u8; HEIGHT] = [
    0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111, 0b00000, 0b00000,
];

/// The rows of `c`'s glyph; a box for a character the font does not have.
pub fn glyph(c: char) -> [u8; HEIGHT] {
    GLYPHS
        .iter()
        .find(|(known, _)| *known == c)
        .map_or(BOX, |(_, rows)| *rows)
}

