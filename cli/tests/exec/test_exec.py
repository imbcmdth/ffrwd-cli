def test_the_printed_loudnorm2_command_runs_in_bash(tmp_path: Path) -> None:
    """The printed line is a POSIX-shell chain, and this is the only test that
    proves it: `eval "$(... | ffrwd loudnorm2env)"` exporting into the
    second command's environment, spliced back through adjacent quotes.

    Skipped where there is no bash (the printed form is POSIX-only by design;
    cmd.exe/PowerShell users have `run`) and where the `ffrwd` console
    script is not installed, since the chain calls it by name. When it is
    installed but the environment was never activated, its directory is put
    on PATH for the shell -- which is what activating would have done.
    """
    # System32's bash.exe is the WSL shim, which hangs when no distro is
    # ready; prefer a real bash (Git Bash on Windows) and prove it answers.
    candidates = [
        shutil.which("bash"),
        r"C:\Program Files\Git\usr\bin\bash.exe",
        r"C:\Program Files\Git\bin\bash.exe",
    ]
    bash = None
    for candidate in candidates:
        if not candidate or not Path(candidate).exists():
            continue
        if "system32" in candidate.lower():
            continue
        try:
            probe = subprocess.run(
                [candidate, "-c", "echo ok"], capture_output=True, text=True, timeout=10
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if probe.returncode == 0 and probe.stdout.strip() == "ok":
            bash = candidate
            break
    if bash is None:
        pytest.skip("no working non-WSL bash found (the printed chain is POSIX-shell only)")
    console_script = shutil.which("ffrwd") or shutil.which(
        "ffrwd", path=str(Path(sys.executable).parent)
    )
    if console_script is None:
        pytest.skip("the ffrwd console script is not installed")
    env = dict(
        os.environ,
        PATH=str(Path(console_script).parent) + os.pathsep + os.environ["PATH"],
    )
    _require_fixture(_AV)
    out_path = tmp_path / "bash.m4a"

    printed = subprocess.run(
        [sys.executable, "-m", "ffrwd", "compile", _loudnorm2_query(_AV, out_path)],
        capture_output=True,
        text=True,
        timeout=_SUBPROCESS_TIMEOUT,
    )
    assert printed.returncode == 0, printed.stderr
    line = printed.stdout.strip()

    result = subprocess.run(
        [bash, "-c", f"set -e\n{line}"],
        capture_output=True,
        text=True,
        timeout=_SUBPROCESS_TIMEOUT,
        env=env,
    )
    assert result.returncode == 0, result.stderr
    assert out_path.exists()
    delivered = float(_measure_loudness(out_path)["FFRWD_LN_I"])
    assert abs(delivered - _LOUDNORM_TARGET_I) <= _LOUDNORM_TOLERANCE_LU


